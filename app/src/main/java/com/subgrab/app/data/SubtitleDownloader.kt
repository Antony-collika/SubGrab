package com.subgrab.app.data
import com.subgrab.app.domain.*
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.MediaFormat
import java.io.File
class SubtitleDownloader(
 private val extractorClient:NewPipeExtractorClient,
 private val downloader:NewPipeDownloader,
 private val pacer:RequestPacer?=null
){
 suspend fun download(video:VideoItem,config:DownloadConfig,outputDir:File):Result<List<File>> =withContext(Dispatchers.IO){
  runCatching{
   suspend fun work():List<File>{
    val url="https://www.youtube.com/watch?v="+video.videoId
    val extractor=extractorClient.streamExtractor(url);extractor.fetchPage()
    val tracks=extractor.getSubtitles(MediaFormat.VTT).filter{t->config.languages.any{w->t.getLanguageTag().equals(w,true)||t.getLanguageTag().startsWith(w+"-")}}.sortedBy{if(config.preferManual&&it.isAutoGenerated())1 else 0}
    if(tracks.isEmpty())throw SubtitleFailure(FailureType.LANGUAGE_UNAVAILABLE,"NewPipeExtractor không tìm thấy subtitle phù hợp")
    val files=mutableListOf<File>()
    tracks.forEach{track->
     val rawVtt=downloader.fetchText(track.content,url);val cues=SubtitleParser.parseWebVtt(rawVtt);val language=track.getLanguageTag()
     val base=video.index.toString().padStart(3,'0')+" - "+FileNameSanitizer.sanitize(video.title)+"-"+language
     if(OutputFormat.SRT in config.formats)files+=write(outputDir,"$base.srt",SubtitleFormatter.format(cues,config.timestampMode))
     if(OutputFormat.TXT in config.formats)files+=write(outputDir,"$base.txt",SubtitleFormatter.format(cues,SubtitleTimestampMode.WITHOUT_TIMESTAMP))
    }
    return workResult(files)
   }
   suspend fun paced():List<File>{return pacer?.execute(RequestOperation(RequestLane.SUBTITLE_EXTRACTOR,"subtitle.fetch","https://www.youtube.com/watch?v="+video.videoId)){work()}?:work()}
   paced()
  }
 }
 private fun workResult(files:List<File>)=files
 private fun write(directory:File,name:String,content:String)=File(directory,name).apply{parentFile?.mkdirs();writeText(content)}
}
class SubtitleFailure(val type:FailureType,message:String):RuntimeException(message)